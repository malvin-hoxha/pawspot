CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;

CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    email varchar(255) NOT NULL,
    name varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    role varchar(16) DEFAULT 'USER' NOT NULL,

    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email)
);

CREATE TABLE public.pet_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area varchar(255),
    city varchar(255) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    description varchar(2000) NOT NULL,
    image_public_id varchar(255),
    image_url varchar(255),
    species varchar(255) NOT NULL,
    status varchar(255) NOT NULL,
    title varchar(255) NOT NULL,
    type varchar(255) NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    user_id bigint NOT NULL,
    version bigint DEFAULT 0 NOT NULL,

    CONSTRAINT pet_posts_species_check
        CHECK (species IN ('CAT', 'DOG', 'OTHER')),

    CONSTRAINT pet_posts_status_check
        CHECK (status IN ('ACTIVE', 'RESOLVED')),

    CONSTRAINT pet_posts_type_check
        CHECK (type IN ('LOST', 'FOUND')),

    CONSTRAINT fk88tq4q0x7wc4y732g468lckw9
        FOREIGN KEY (user_id) REFERENCES public.users(id)
);

CREATE TABLE public.conversations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    interested_user_id bigint NOT NULL,
    post_id bigint NOT NULL,

    CONSTRAINT uk_conversation_post_interested
        UNIQUE (post_id, interested_user_id),

    CONSTRAINT fka9g8j3acm53wqgflbecnebxyx
        FOREIGN KEY (post_id)
        REFERENCES public.pet_posts(id)
        ON DELETE CASCADE,

    CONSTRAINT fkrmvl6m5pujc7ljasb98lmi1me
        FOREIGN KEY (interested_user_id)
        REFERENCES public.users(id)
        ON DELETE CASCADE
);

CREATE TABLE public.messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body varchar(2000) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    conversation_id bigint NOT NULL,
    sender_id bigint NOT NULL,

    CONSTRAINT fkt492th6wsovh1nush5yl5jj8e
        FOREIGN KEY (conversation_id)
        REFERENCES public.conversations(id)
        ON DELETE CASCADE,

    CONSTRAINT fk4ui4nnwntodh6wjvck53dbk9m
        FOREIGN KEY (sender_id)
        REFERENCES public.users(id)
        ON DELETE CASCADE
);

CREATE TABLE public.post_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    description varchar(1000),
    reason varchar(255) NOT NULL,

    -- Preserve the original post ID after the foreign key is cleared.
    reported_post_id bigint NOT NULL,

    status varchar(255) NOT NULL,
    post_id bigint,
    reporter_id bigint,

    CONSTRAINT post_reports_reason_check
        CHECK (reason IN (
            'SPAM',
            'MISLEADING_CONTENT',
            'INAPPROPRIATE_CONTENT',
            'PERSONAL_DATA',
            'OTHER'
        )),

    CONSTRAINT post_reports_status_check
        CHECK (status IN ('PENDING', 'DISMISSED', 'POST_REMOVED')),

    CONSTRAINT fkntjpsng8t3wa4t0qswquw4rjo
        FOREIGN KEY (post_id)
        REFERENCES public.pet_posts(id)
        ON DELETE SET NULL,

    CONSTRAINT fkqi5fmh45u32i63971en0rmrvo
        FOREIGN KEY (reporter_id)
        REFERENCES public.users(id)
        ON DELETE SET NULL
);

CREATE TABLE public.refresh_sessions (
    id varchar(255) PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    revoked_at timestamp(6) with time zone,
    user_id bigint NOT NULL,
    expires_at timestamp with time zone NOT NULL,

    CONSTRAINT fk9ndfh1op1iy3xuqyi6gxkseg0
        FOREIGN KEY (user_id) REFERENCES public.users(id)
);

CREATE TABLE public.refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    family_id varchar(255) NOT NULL,
    revoked_at timestamp(6) with time zone,
    token_id varchar(255) NOT NULL,
    user_id bigint NOT NULL,

    CONSTRAINT ukkt71wnjd35heo0p6pewmrdf5f
        UNIQUE (token_id),

    CONSTRAINT fk1lih5y2npsf8u5o3vhdb9y0os
        FOREIGN KEY (user_id) REFERENCES public.users(id)
);

CREATE INDEX idx_refresh_sessions_expires_at
    ON public.refresh_sessions (expires_at);

CREATE INDEX idx_refresh_tokens_expires_at
    ON public.refresh_tokens (expires_at);